"""Archive every Marvisak/VIctory thread neonbyte1 is involved in as Markdown.

Usage: python3 archive.py <output dir>
Writes threads/<number>.md (body, comments, reviews, review comments in
time order) and README.md (index). Idempotent: rerun to refresh.
"""

import json
import subprocess
import sys
from pathlib import Path

REPO = "Marvisak/VIctory"
WHO = "neonbyte1"


def api(path, *args):
    out = subprocess.run(
        ["gh", "api", "--paginate", "--slurp", path, *args],
        capture_output=True, text=True, check=True,
    ).stdout
    pages = json.loads(out)
    items = []
    for page in pages:
        items.extend(page.get("items", []) if isinstance(page, dict) else page)
    return items


def search(q):
    return api(f"search/issues?q={q.replace(' ', '+').replace(':', '%3A')}&per_page=100")


def entry(kind, user, when, url, body, extra=""):
    return when or "", f"### {kind} by @{user} — {when}{extra}\n\n<{url}>\n\n{(body or '').strip()}\n"


def thread(n, is_pr):
    meta = json.loads(subprocess.run(
        ["gh", "api", f"repos/{REPO}/issues/{n}"], capture_output=True, text=True, check=True
    ).stdout)
    parts = []
    for c in api(f"repos/{REPO}/issues/{n}/comments?per_page=100"):
        parts.append(entry("Comment", (c["user"] or {"login": "ghost"})["login"], c["created_at"], c["html_url"], c["body"]))
    if is_pr:
        for r in api(f"repos/{REPO}/pulls/{n}/reviews?per_page=100"):
            if r.get("body") or r["state"] != "COMMENTED":
                parts.append(entry(f"Review ({r['state']})", (r["user"] or {"login": "ghost"})["login"], r.get("submitted_at"),
                                   r["html_url"], r.get("body")))
        for c in api(f"repos/{REPO}/pulls/{n}/comments?per_page=100"):
            parts.append(entry("Review comment", (c["user"] or {"login": "ghost"})["login"], c["created_at"], c["html_url"],
                               c["body"], f" on `{c['path']}`"))
    parts.sort(key=lambda p: p[0])
    kind = "PR" if is_pr else "Issue"
    head = (f"# {REPO}#{n}: {meta['title']}\n\n"
            f"- {kind} by @{(meta["user"] or {"login": "ghost"})["login"]}, opened {meta['created_at']}, state **{meta['state']}**"
            f"{' (merged)' if is_pr and meta.get('pull_request', {}).get('merged_at') else ''}\n"
            f"- <{meta['html_url']}>\n- Archived copy; the original thread is authoritative while it exists.\n\n"
            f"## Description\n\n{(meta.get('body') or '').strip()}\n\n## Discussion\n\n")
    return meta, head + "\n".join(p[1] for p in parts)


def main():
    out = Path(sys.argv[1])
    (out / "threads").mkdir(parents=True, exist_ok=True)
    rows = []
    for it in search(f"repo:{REPO} involves:{WHO}"):
        n = it["number"]
        meta, text = thread(n, "pull_request" in it)
        (out / "threads" / f"{n}.md").write_text(text, encoding="utf-8")
        rows.append((n, meta["title"].replace("|", "\\|"), "PR" if "pull_request" in it else "issue",
                     (meta["user"] or {"login": "ghost"})["login"], meta["state"]))
    rows.sort()
    index = ["# Archive of upstream threads", "",
             f"Every {REPO} issue and PR that @{WHO} took part in, copied as Markdown so results survive "
             "if upstream goes private or down. Regenerated by `archive.py`; posts keep their authors and links.",
             "", "| # | Kind | Author | State | Title |", "|---|---|---|---|---|"]
    index += [f"| [{n}](threads/{n}.md) | {k} | @{a} | {s} | {t} |" for n, t, k, a, s in rows]
    (out / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print(len(rows), "threads")


if __name__ == "__main__":
    main()
